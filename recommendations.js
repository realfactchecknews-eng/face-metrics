function getSymmetryNote(score) {
  const pct = Math.round(score * 100);
  if (pct >= 90) return `${pct}% — высокая симметрия, в пределах обычной природной вариации.`;
  if (pct >= 75) return `${pct}% — умеренная асимметрия, это нормально и почти не заметно визуально.`;
  return `${pct}% — заметная асимметрия. Напоминаем: асимметрия лица — это физиологическая норма, а не недостаток.`;
}

function buildRecommendations(faceShapeInfo) {
  const haircuts = HAIRCUT_RECS[faceShapeInfo.shape] || HAIRCUT_RECS["овальное (oval)"];
  return {
    haircuts,
    styleNotes: GENERAL_STYLE_NOTES,
  };
}
